-- Additive recovery support; existing records and receipt objects are preserved.
BEGIN;
ALTER TABLE public.expenses ADD COLUMN IF NOT EXISTS deleted_at text;
ALTER TABLE public.expenses ADD COLUMN IF NOT EXISTS deleted_by text;
CREATE INDEX IF NOT EXISTS expenses_deleted_idx ON public.expenses(deleted_at);
CREATE TABLE IF NOT EXISTS personnel.expense_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id text NOT NULL, actor text NOT NULL,
 action text NOT NULL CHECK(action IN ('delete','restore')),
 at timestamptz NOT NULL DEFAULT now(), before_document jsonb NOT NULL, after_document jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS expense_events_expense_idx ON personnel.expense_events(expense_id,id DESC);
ALTER TABLE personnel.expense_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON personnel.expense_events FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE personnel.expense_events_id_seq FROM PUBLIC,anon,authenticated;
COMMIT;
NOTIFY pgrst, 'reload schema';
