-- Private order storage; no photos and no additions to Clip sales.
BEGIN;
CREATE TABLE IF NOT EXISTS personnel.inventory_orders (
 id text PRIMARY KEY, folio text NOT NULL UNIQUE, received_on date NOT NULL,
 document jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS inventory_received ON personnel.inventory_orders(received_on);
CREATE TABLE IF NOT EXISTS personnel.inventory_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id text NOT NULL REFERENCES personnel.inventory_orders(id) ON DELETE CASCADE,
 actor text NOT NULL, action text NOT NULL, at timestamptz NOT NULL DEFAULT now(), details text NOT NULL
);
CREATE TABLE IF NOT EXISTS personnel.inventory_requests (
 request_id text PRIMARY KEY, order_id text NOT NULL REFERENCES personnel.inventory_orders(id) ON DELETE CASCADE,
 actor text NOT NULL, fingerprint text NOT NULL
);
ALTER TABLE personnel.inventory_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE personnel.inventory_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE personnel.inventory_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON personnel.inventory_orders,personnel.inventory_events,personnel.inventory_requests FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE personnel.inventory_events_id_seq FROM PUBLIC,anon,authenticated;
COMMIT;
