-- Additive personnel storage. No changes to Clip, expenses, or receipt tables.
BEGIN;
CREATE SCHEMA IF NOT EXISTS personnel;
REVOKE ALL ON SCHEMA personnel FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS personnel.workers (
 id text PRIMARY KEY, name text NOT NULL CHECK(length(name) BETWEEN 1 AND 80),
 username text NOT NULL UNIQUE CHECK(username ~ '^[a-z0-9][a-z0-9._-]{2,39}$'),
 role text NOT NULL CHECK(role IN ('lavador','detallador')),
 active integer NOT NULL DEFAULT 1 CHECK(active IN (0,1)), pin_hash text
);
CREATE TABLE IF NOT EXISTS personnel.shifts (
 id text PRIMARY KEY, worker_id text NOT NULL REFERENCES personnel.workers(id),
 role text NOT NULL CHECK(role IN ('lavador','detallador')), rate_cents integer NOT NULL CHECK(rate_cents>0),
 started_at timestamptz NOT NULL, ended_at timestamptz CHECK(ended_at>started_at), request_id text NOT NULL UNIQUE
);
CREATE UNIQUE INDEX IF NOT EXISTS one_open_shift ON personnel.shifts(worker_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS shift_dates ON personnel.shifts(started_at,ended_at);
CREATE TABLE IF NOT EXISTS personnel.sessions (
 token_hash text PRIMARY KEY, worker_id text NOT NULL REFERENCES personnel.workers(id), expires double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS session_expiry ON personnel.sessions(expires);
CREATE TABLE IF NOT EXISTS personnel.attempts (username text PRIMARY KEY,count integer NOT NULL,until_ms double precision NOT NULL);
CREATE TABLE IF NOT EXISTS personnel.audit (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shift_id text NOT NULL REFERENCES personnel.shifts(id),
 actor text NOT NULL, reason text NOT NULL, before_json text NOT NULL, after_json text NOT NULL, created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS personnel.settings (key text PRIMARY KEY,value text NOT NULL);
ALTER TABLE personnel.workers ENABLE ROW LEVEL SECURITY;
ALTER TABLE personnel.shifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE personnel.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE personnel.attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE personnel.audit ENABLE ROW LEVEL SECURITY;
ALTER TABLE personnel.settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA personnel FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA personnel FROM PUBLIC, anon, authenticated;
COMMIT;

-- Idempotency receipts for the shared-phone clock. No worker session is retained.
BEGIN;
CREATE TABLE IF NOT EXISTS personnel.clock_requests (
 request_id text PRIMARY KEY, worker_id text NOT NULL REFERENCES personnel.workers(id),
 operation text NOT NULL CHECK(operation IN ('in','out')),
 shift_id text NOT NULL REFERENCES personnel.shifts(id), created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE personnel.clock_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON personnel.clock_requests FROM PUBLIC, anon, authenticated;
COMMIT;
